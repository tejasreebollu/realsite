import assert from 'node:assert/strict';
import { updateSearchFilters } from '../src/boundary-search.js';
const start = { q: 'Hyderabad', polygon: '', boundary_q: '', beds: 2, max_price: 10000000, purpose: 'sale' };
const drawn = updateSearchFilters(start, { polygon: 'shape' });
assert.equal(drawn.q, '');
assert.equal(drawn.boundary_q, 'Hyderabad');
assert.deepEqual(updateSearchFilters(drawn, { polygon: '' }), start);
const edited = updateSearchFilters(drawn, { polygon: 'edited shape' });
assert.equal(edited.boundary_q, 'Hyderabad');
assert.equal(updateSearchFilters(edited, { polygon: '' }).q, 'Hyderabad');
const changed = updateSearchFilters(drawn, { beds: 3, purpose: 'rent' });
assert.equal(updateSearchFilters(changed, { polygon: '' }).beds, 3);
assert.equal(updateSearchFilters(changed, { polygon: '' }).purpose, 'rent');
const location = updateSearchFilters(drawn, { q: 'Pune' });
assert.equal(location.q, 'Pune');
assert.equal(location.polygon, '');
assert.equal(location.boundary_q, '');
assert.equal(updateSearchFilters(drawn, { polygon: '', boundary_q: '', q: '', beds: 0 }).q, 'Hyderabad');
const worldwide = updateSearchFilters({ ...start, q: '' }, { polygon: 'shape' });
assert.equal(updateSearchFilters(worldwide, { polygon: '' }).q, '');
const legacy = { ...drawn }; delete legacy.boundary_q;
assert.equal(updateSearchFilters(legacy, { polygon: '' }).q, '');
assert.deepEqual(start, { q: 'Hyderabad', polygon: '', boundary_q: '', beds: 2, max_price: 10000000, purpose: 'sale' });
console.log('Boundary location restoration checks passed.');
