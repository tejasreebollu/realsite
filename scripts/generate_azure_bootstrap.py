"""Generate the portable PostgreSQL schema-and-demo-data bootstrap file.

The generated SQL deliberately contains fictional property inventory only. It
does not contain local accounts, password hashes, enquiries, uploads, saved
searches, session tokens or any other local/private records.
"""
from __future__ import annotations

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data" / "demo-properties.json"
DESTINATION = ROOT / "data" / "azure-postgres-bootstrap.sql"
CITIES = ("Hyderabad", "Bengaluru", "Mumbai", "Pune", "New Delhi")
ACTIVE_INDICES = (*range(12), *range(16, 24))

SCHEMA = r'''-- RealSite PostgreSQL bootstrap for Azure Database for PostgreSQL.
-- Generated from data/demo-properties.json by scripts/generate_azure_bootstrap.py.
-- It is safe to run repeatedly: tables/indexes are created if absent and
-- synthetic properties are identified by their stable seed_key.
-- This file is for a new or dedicated demo database. It never drops tables.
-- No users, passwords, sessions, enquiries, uploaded files or private local
-- data are included. The 100 fictional listings are intentionally unowned.
\set ON_ERROR_STOP on
BEGIN;

CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(254) NOT NULL UNIQUE,
  password_hash VARCHAR(256) NOT NULL,
  role VARCHAR(20) NOT NULL DEFAULT 'user',
  active BOOLEAN NOT NULL DEFAULT TRUE,
  phone VARCHAR(20) NOT NULL DEFAULT '',
  city VARCHAR(100) NOT NULL DEFAULT '',
  bio TEXT NOT NULL DEFAULT '',
  avatar_url VARCHAR(250) NOT NULL DEFAULT '',
  demo BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS auth_sessions (
  token_hash VARCHAR(64) PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS properties (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  seed_key VARCHAR(120) UNIQUE,
  title VARCHAR(160) NOT NULL,
  address VARCHAR(250) NOT NULL,
  city VARCHAR(100) NOT NULL,
  state VARCHAR(100) NOT NULL,
  pincode VARCHAR(6) NOT NULL,
  price INTEGER NOT NULL,
  beds INTEGER NOT NULL,
  baths INTEGER NOT NULL,
  sqft INTEGER NOT NULL,
  kind VARCHAR(30) NOT NULL,
  purpose VARCHAR(10) NOT NULL,
  lat DOUBLE PRECISION NOT NULL,
  lng DOUBLE PRECISION NOT NULL,
  images JSONB NOT NULL,
  amenities JSONB NOT NULL,
  description TEXT NOT NULL,
  features JSONB,
  previous_price INTEGER,
  badge VARCHAR(80) NOT NULL DEFAULT 'New listing',
  agent VARCHAR(120) NOT NULL,
  owner_id INTEGER REFERENCES users(id),
  demo BOOLEAN NOT NULL DEFAULT FALSE,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  area_unit VARCHAR(10) NOT NULL DEFAULT 'sqft',
  area_value DOUBLE PRECISION,
  plot_use VARCHAR(20) NOT NULL DEFAULT '',
  plot_facing VARCHAR(20) NOT NULL DEFAULT '',
  road_width_ft INTEGER,
  plot_approval VARCHAR(100) NOT NULL DEFAULT '',
  deposit INTEGER NOT NULL DEFAULT 0,
  furnishing VARCHAR(20) NOT NULL DEFAULT 'Unfurnished',
  available_from VARCHAR(10),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS uploaded_images (
  id VARCHAR(32) PRIMARY KEY,
  owner_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  width INTEGER NOT NULL,
  height INTEGER NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS favorites (
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  property_id INTEGER NOT NULL REFERENCES properties(id) ON DELETE CASCADE,
  PRIMARY KEY (user_id, property_id)
);
CREATE TABLE IF NOT EXISTS saved_searches (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name VARCHAR(100) NOT NULL,
  filters JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS inquiries (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id),
  property_id INTEGER NOT NULL REFERENCES properties(id),
  message TEXT NOT NULL,
  phone VARCHAR(20) NOT NULL,
  visit_date VARCHAR(30),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS agent_profiles (
  user_id INTEGER PRIMARY KEY REFERENCES users(id),
  agency VARCHAR(120) NOT NULL,
  bio TEXT NOT NULL,
  service_areas JSONB NOT NULL,
  experience_years INTEGER NOT NULL,
  registration_number VARCHAR(100) NOT NULL DEFAULT '',
  publish_phone BOOLEAN NOT NULL DEFAULT FALSE,
  status VARCHAR(20) NOT NULL DEFAULT 'pending',
  review_note VARCHAR(1000) NOT NULL DEFAULT '',
  reviewed_by INTEGER REFERENCES users(id),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS email_changes (
  user_id INTEGER PRIMARY KEY REFERENCES users(id),
  email VARCHAR(254) NOT NULL,
  token_hash VARCHAR(64) NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS account_audit (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id INTEGER NOT NULL REFERENCES users(id),
  target_id INTEGER NOT NULL REFERENCES users(id),
  action VARCHAR(60) NOT NULL,
  reason VARCHAR(1000) NOT NULL DEFAULT '',
  changes JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_users_email ON users (email);
CREATE INDEX IF NOT EXISTS ix_properties_seed_key ON properties (seed_key);
CREATE INDEX IF NOT EXISTS ix_properties_city ON properties (city);
CREATE INDEX IF NOT EXISTS ix_properties_price ON properties (price);
CREATE INDEX IF NOT EXISTS ix_properties_purpose ON properties (purpose);
CREATE INDEX IF NOT EXISTS ix_uploaded_images_owner_id ON uploaded_images (owner_id);
CREATE INDEX IF NOT EXISTS ix_saved_searches_user_id ON saved_searches (user_id);
CREATE INDEX IF NOT EXISTS ix_inquiries_user_id ON inquiries (user_id);
CREATE INDEX IF NOT EXISTS ix_agent_profiles_status ON agent_profiles (status);
CREATE INDEX IF NOT EXISTS ix_account_audit_actor_id ON account_audit (actor_id);
CREATE INDEX IF NOT EXISTS ix_account_audit_target_id ON account_audit (target_id);

'''

COLUMNS = (
    "seed_key", "title", "address", "city", "state", "pincode", "price",
    "beds", "baths", "sqft", "kind", "purpose", "lat", "lng", "images",
    "amenities", "description", "features", "previous_price", "badge", "agent",
    "demo", "active", "area_unit", "area_value", "plot_use", "plot_facing",
    "road_width_ft", "plot_approval", "deposit", "furnishing", "available_from",
    "created_at",
)


def sql_literal(value):
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, (list, dict)):
        encoded = json.dumps(value, ensure_ascii=False, separators=(",", ":"))
        return "'" + encoded.replace("'", "''") + "'::jsonb"
    return "'" + str(value).replace("'", "''") + "'"


def seed_key(properties, item):
    city_position = properties[item["city"]].index(item)
    return f"india-demo-v2:{item['city']}:{ACTIVE_INDICES[city_position]}"


def main():
    document = json.loads(SOURCE.read_text(encoding="utf-8"))
    items = document["properties"]
    assert document["synthetic"] and document["count"] == len(items) == 100
    by_city = {city: [item for item in items if item["city"] == city] for city in CITIES}
    assert all(len(rows) == 20 for rows in by_city.values())
    values = []
    for item in items:
        row = dict(item)
        row["seed_key"] = seed_key(by_city, item)
        values.append("(" + ", ".join(sql_literal(row[column]) for column in COLUMNS) + ")")
    sql = SCHEMA
    sql += "INSERT INTO properties (" + ", ".join(COLUMNS) + ") VALUES\n  "
    sql += ",\n  ".join(values)
    sql += "\nON CONFLICT (seed_key) DO NOTHING;\n\n"
    sql += "COMMIT;\n"
    DESTINATION.write_text(sql, encoding="utf-8", newline="\n")
    print(f"Generated {DESTINATION} with {len(items)} synthetic properties.")


if __name__ == "__main__":
    main()
